import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright-core';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const url='http://127.0.0.1:4174/radar-ia-portal/';
const chrome=process.env.RADAR_CHROME_PATH||'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4174','--strictPort'],{cwd:root,stdio:'ignore'});
let browser;
async function ready(){
 for(let i=0;i<65;i++){try{if((await fetch(url)).status===200)return}catch{}
  await new Promise(r=>setTimeout(r,300))}
 throw new Error('Prévia Vite não iniciou');
}
try{
 await ready();
 browser=await chromium.launch({headless:true,executablePath:chrome,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:390,height:844},permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.locator('.hero-copy h1').waitFor();
 assert.match(await page.locator('.hero-copy h1').innerText(),/O que mudou/);
 await page.locator('.home-impact-card').first().waitFor({timeout:12000});
 assert.equal(await page.locator('.home-impact-card').count(),3);
 const mobile=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.equal(mobile.width,390);assert.equal(mobile.scroll,390);
 console.log('OK: home mostra três referências verificadas sem transbordamento');
 await page.getByRole('button',{name:/Montar meu Radar/}).click();
 await page.locator('.impact-card').first().waitFor({timeout:12000});
 assert.equal(await page.locator('.impact-card').count(),4);
 await page.locator('.legislative-monitor-grid').waitFor({timeout:9000});
 assert.match(await page.locator('.legislative-monitor').innerText(),/Aguardando Parecer/);
 assert.match(await page.locator('.watch-summary').innerText(),/4 fichas/);
 console.log('OK: meu radar consulta quatro fichas reais do banco');
 await page.locator('.watch-choices button').filter({hasText:'Dados dos clientes'}).click();
 assert.equal(await page.locator('.impact-card').count(),1);
 assert.match(await page.locator('.impact-card').innerText(),/ANPD/);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('.hero-copy h1').waitFor();
 await page.locator('.bottom-nav').getByRole('button',{name:'Meu Radar'}).click();
 await page.locator('.impact-card').first().waitFor();
 assert.equal(await page.locator('.impact-card').count(),1,'Interesse deveria persistir após reabrir');
 console.log('OK: assuntos persistem sem cadastro após atualizar a página');
 await page.getByRole('button',{name:/Ver o que conferir/}).first().click();
 assert.match(await page.locator('.impact-next').innerText(),/Consulte o guia/);
 await page.getByRole('button',{name:/Guardar/}).first().click();
 await page.getByRole('button',{name:/Salvos/}).click();
 assert.equal(await page.locator('.impact-card').count(),1);
 await page.getByRole('button',{name:/Meu resumo/}).click();
 await page.getByRole('button',{name:/Copiar resumo com fontes/}).click();
 await page.getByRole('status').waitFor({timeout:6000});
 const clip=await page.evaluate(()=>navigator.clipboard.readText());
 assert.match(clip,/gov.br\/anpd/);
 assert.match(clip,/Verificado em/);
 console.log('OK: acompanhamento, favoritos e resumo com fontes');
 await page.locator('.bottom-nav').getByRole('button',{name:'Ferramentas'}).click();
 await page.locator('.guide-card').first().waitFor({timeout:6000});
 assert.equal(await page.locator('.guide-card').count(),4);
 await page.getByRole('tab',{name:/Conferir resposta da IA/}).click();
 assert.equal(await page.locator('.verification-list label').count(),6);
 await page.locator('.verification-list label').first().click();
 assert.match(await page.locator('.tool-progress').innerText(),/1 de 6/);
 console.log('OK: antigas ferramentas preservadas');
 await page.getByRole('tab',{name:/Montar um prompt/}).click();
 await page.locator('#goal').fill('Documentação fictícia sem dados pessoais');
 await page.getByRole('button',{name:/Copiar prompt/}).click();
 await page.getByRole('button',{name:/Copiado/}).waitFor({timeout:4000});
 assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/Documentação fictícia/);
 console.log('OK: gerador de prompts continua funcionando');
 await page.locator('.bottom-nav').getByRole('button',{name:'Fontes'}).click();
 assert.match(await page.locator('.page-intro h1').innerText(),/O que mudou/);
 await page.locator('.search-field input').fill('prompt');
 assert.match(await page.locator('.filter-row').innerText(),/resultado/);
 await page.locator('.bottom-nav').getByRole('button',{name:'Avisos'}).click();
 assert.match(await page.locator('.page-intro h1').innerText(),/Informes/);
 assert.deepEqual(errors,[],'Erros JavaScript: '+errors.join(' | '));
 console.log('OK: páginas de notícias e informes preservadas, sem erro JS');
 await context.close();
 const desktop=await browser.newContext({viewport:{width:1440,height:900}});
 const desk=await desktop.newPage();await desk.goto(url,{waitUntil:'domcontentloaded'});
 assert.equal(await desk.locator('.desktop-links button').count(),5);
 await desk.getByRole('button',{name:'Meu Radar'}).first().click();
 await desk.locator('.impact-card').first().waitFor({timeout:7000});
 const metrics=await desk.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.equal(metrics.width,metrics.scroll);
 console.log('OK: interface desktop sem rolagem horizontal');
 await desktop.close();
 console.log('SMOKE UI V1.3: SUCESSO');
}catch(e){console.error('FALHA UI V1.3:',e);process.exitCode=1}
finally{if(browser)await browser.close();server.kill()}
